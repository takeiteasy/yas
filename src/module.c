void ensure_registry(void)
{
    if (yas_nilp(yas_library_registry))
        yas_library_registry = yas_make_hash();
}

static void ensure_search_paths(void)
{
    if (!yas_nilp(yas_global_search_paths))
        return;

    /* Named locals, rooted, built one at a time: each yas_make_string()
     * result is an unrooted C temporary until the yas_cons() consuming it
     * returns, but a *sibling* argument's own allocating call can step
     * the GC first and free it before it's ever linked in. */
    YasAtom lib_dir = yas_make_string("./lib");
    yas_gc_push_root(&lib_dir);
    YasAtom cwd_dir = yas_make_string(".");
    yas_gc_push_root(&cwd_dir);
    YasAtom tail = yas_cons(cwd_dir, yas_nil);
    yas_gc_push_root(&tail);
    /* lib_dir/tail must both stay rooted through this final yas_cons
     * call too - they're its arguments, still unlinked into anything
     * until it returns. */
    yas_global_search_paths = yas_cons(lib_dir, tail);
    yas_gc_pop_roots(3); /* tail, cwd_dir, lib_dir */
}

/* Public API for embedders: eagerly loads every native module (C part +
 * any embedded Lisp layer) up front rather than lazily on first `import`.
 * Goes through load_module() so eager and lazy loading produce identical
 * records - an embedder that calls this gets working modules even if it
 * never goes through yas_module_import() at all. */
static void yas_load_all_modules_impl(void)
{
    ensure_registry();
    ensure_search_paths();

    for (int i = 0; native_modules[i].name; i++) {
        YasAtom ignore;
        load_module(native_modules[i].name, &ignore);
    }
}

void yas_load_all_modules(void)
{
    yas_load_all_modules_impl();
}


/* Lowercase a module-name symbol into its canonical registry key
 * ("YAS/BASE" -> "yas/base"). Returns a malloc'd string, or NULL if
 * `sym` is not a symbol. */
static char *module_key_from_symbol(YasAtom sym)
{
    if (sym.type != YAS_ATOM_TYPE_SYMBOL)
        return NULL;

    const char *s = sym.value.symbol;
    size_t n = strlen(s);
    char *out = malloc(n + 1);
    for (size_t i = 0; i < n; i++) {
        char c = s[i];
        out[i] = (c >= 'A' && c <= 'Z') ? (char)(c + 32) : c;
    }
    out[n] = '\0';
    return out;
}

/* Try one directory for "<dir>/<key>.ys"; returns a malloc'd path the
 * caller must free, or NULL. Paths are sized dynamically - no fixed
 * buffers. */
static char *try_module_dir(const char *dir, const char *key)
{
    size_t n = strlen(dir) + strlen(key) + sizeof("/.ys");
    char *full_path = malloc(n);
    snprintf(full_path, n, "%s/%s.ys", dir, key);

    FILE *f = fopen(full_path, "r");
    if (f) {
        fclose(f);
        return full_path;
    }
    free(full_path);
    return NULL;
}

/* Filesystem resolution: the directory of the file doing the importing
 * first (so a project's own modules resolve relative to that project),
 * then the global search paths. Returns a malloc'd path or NULL. */
static char *find_module_file(const char *key)
{
    if (yas_current_file_path) {
        const char *last_slash = strrchr(yas_current_file_path, '/');
        if (last_slash) {
            size_t dir_len = (size_t)(last_slash - yas_current_file_path);
            char *dir = malloc(dir_len + 1);
            memcpy(dir, yas_current_file_path, dir_len);
            dir[dir_len] = '\0';
            char *hit = try_module_dir(dir, key);
            free(dir);
            if (hit)
                return hit;
        }
    }

    YasAtom paths = yas_global_search_paths;
    while (!yas_nilp(paths)) {
        YasAtom dir = yas_car(paths);
        if (dir.type == YAS_ATOM_TYPE_STRING) {
            char *hit = try_module_dir(dir.value.string, key);
            if (hit)
                return hit;
        }
        paths = yas_cdr(paths);
    }
    return NULL;
}

/* Create a fresh module record in LOADING state and register it under
 * `key` BEFORE any of its forms evaluate - both the cycle guard (a
 * re-entrant import sees LOADING and errors instead of recursing) and
 * the reachability story (from registration on, the record is reachable
 * via the GC-rooted registry, so callers need no local root to hold it
 * across the body-evaluating call). The module env chains to `parent`
 * (yas/base's env - the builtins layer; see load_module()). */
static void make_module(const char *key_str, YasAtom key, const char *path, YasAtom parent_env,
                        YasAtom *out_lib, YasAtom *out_env)
{
    YasAtom lib = yas_make_hash();
    /* `lib` is fresh and otherwise-unreachable until the registry insert
     * at the bottom - root it across every allocating call above. */
    yas_gc_push_root(&lib);

    yas_hash_set(lib, yas_make_sym("*NAME*"), yas_make_string(key_str));
    yas_hash_set(lib, yas_make_sym("*STATE*"), yas_make_sym(MODULE_STATE_LOADING));
    yas_hash_set(lib, yas_make_sym("*PATH*"),
                 path ? yas_make_string(path) : yas_nil);
    *out_env = yas_env_create(parent_env);
    /* Mark the boundary for yas_env_set(): set! from inside this
     * module shadows here instead of writing through to shared base. */
    (*out_env).value.env->module_boundary = 1;
    yas_hash_set(lib, yas_make_sym("*ENV*"), *out_env);

    yas_hash_set(yas_library_registry, key, lib);
    yas_gc_pop_roots(1); /* lib */
    *out_lib = lib;
}

static void module_set_ready(YasAtom lib)
{
    yas_hash_set(lib, yas_make_sym("*STATE*"), yas_make_sym(MODULE_STATE_READY));
}

/* Remove a failed module's record so a later retry reports the real
 * problem ("not found" / the body's own error) rather than a stale
 * circular-import complaint about the abandoned placeholder. */
static void module_unregister(const char *key_str, YasAtom key)
{
    (void)yas_hash_remove(yas_library_registry, key);
    (void)key_str;
}

/* If a native module has an embedded Lisp layer in stdlib.h, evaluate it
 * straight into the module's own env. Unlike the old define-library flow
 * there is no self-registration trickery: the record already exists, so
 * the source just extends it. */
static int merge_embedded_source(const char *key_str, YasAtom lib)
{
    for (int i = 0; stdlib_files[i].name; i++) {
        if (strcmp(key_str, stdlib_files[i].name) != 0)
            continue;
        YasAtom env = yas_hash_ref(lib, yas_make_sym("*ENV*"), yas_nil);
        /* `env` stays reachable via lib -> registry throughout the eval,
         * so no local root is needed (docs/GC.md: locals holding atoms
         * that are reachable from a root elsewhere need no root of their
         * own). */
        YasAtom ignore;
        return yas_eval_source(stdlib_files[i].source, key_str, env, &ignore);
    }
    return YAS_ERROR_OK;
}

/* Load (or fetch from cache) the module named `key_str`. On success
 * returns YAS_ERROR_OK with the record in *out_lib; every failure raises
 * a module-error exception and returns non-zero. */
static int load_module(const char *key_str, YasAtom *out_lib)
{
    ensure_registry();
    ensure_search_paths();

    YasAtom key = yas_make_string(key_str);
    /* `key` is a fresh, otherwise-unreachable string used purely for
     * registry lookups below, and every branch can trigger nested module
     * loads (which allocate enough to legitimately step the collector).
     * One root covers the whole function since yas_gc_push_root() tracks
     * the slot's address, not a snapshot of its value. Without this, the
     * string can be collected mid-load, its memory reused by another
     * allocation, and a post-load re-lookup silently compares against a
     * different module's name - the exact failure mode documented in
     * docs/GC.md's history of this function. */
    yas_gc_push_root(&key);

    YasAtom lib = yas_hash_ref(yas_library_registry, key, yas_nil);
    if (!yas_nilp(lib)) {
        YasAtom state = yas_hash_ref(lib, yas_make_sym("*STATE*"), yas_nil);
        if (state.type == YAS_ATOM_TYPE_SYMBOL &&
            strcmp(state.value.symbol, MODULE_STATE_LOADING) == 0) {
            yas_gc_pop_roots(1); /* key */
            char msg[256];
            snprintf(msg, sizeof(msg), "circular import: '%s' is already being loaded",
                     key_str);
            return yas_raise_error("module-error", msg);
        }
        yas_gc_pop_roots(1); /* key */
        *out_lib = lib;
        return YAS_ERROR_OK;
    }

    /* Every module env chains to yas/base's env as its PARENT - the
     * shared builtins layer (like Python's builtins, one frame behind
     * every module). This is what keeps a module's public surface equal
     * to its own top-level bindings: imports enumerate the module's own
     * frame only (yas_env_keys is frame-exact), so base's names are
     * visible to the module's code but never re-exported through it.
     * yas/base itself IS that root frame. Loading base first also
     * guarantees every module body runs with the builtins in place.
     * `parent` stays reachable via base's registry record for the rest
     * of this function, so it needs no local root. */
    YasAtom parent = yas_nil;
    if (strcmp(key_str, "yas/base") != 0) {
        YasAtom base_lib = yas_nil;
        int berr = load_module("yas/base", &base_lib);
        if (berr) {
            yas_gc_pop_roots(1); /* key */
            return berr;
        }
        parent = yas_hash_ref(base_lib, yas_make_sym("*ENV*"), yas_nil);
    }

    /* Native C module first (embedded beats filesystem). The loader
     * creates and registers the record; any embedded Lisp layer then
     * merges directly into its env. */
    for (int i = 0; native_modules[i].name; i++) {
        if (strcmp(key_str, native_modules[i].name) == 0) {
            native_modules[i].loader(parent);
            lib = yas_hash_ref(yas_library_registry, key, yas_nil);
            if (yas_nilp(lib)) {
                yas_gc_pop_roots(1); /* key */
                return yas_raise_error("module-error",
                                       "internal: native module loader did not register");
            }
            int err = merge_embedded_source(key_str, lib);
            if (err) {
                module_unregister(key_str, key);
                yas_gc_pop_roots(1); /* key */
                return err;
            }
            yas_gc_pop_roots(1); /* key */
            *out_lib = lib;
            return YAS_ERROR_OK;
        }
    }

    /* Pure-Lisp embedded stdlib (no C part, e.g. format/test). */
    for (int i = 0; stdlib_files[i].name; i++) {
        if (strcmp(key_str, stdlib_files[i].name) == 0) {
            YasAtom mod_env;
            make_module(key_str, key, "<builtin>", parent, &lib, &mod_env);

            YasAtom ignore;
            int err = yas_eval_source(stdlib_files[i].source, key_str, mod_env, &ignore);
            if (err) {
                module_unregister(key_str, key);
                yas_gc_pop_roots(1); /* key */
                return err;
            }
            module_set_ready(lib);
            yas_gc_pop_roots(1); /* key */
            *out_lib = lib;
            return YAS_ERROR_OK;
        }
    }

    /* Filesystem fallback. */
    char *path = find_module_file(key_str);
    if (!path) {
        yas_gc_pop_roots(1); /* key */
        char msg[256];
        snprintf(msg, sizeof(msg), "module not found: '%s' (searched importer directory "
                                   "and search paths for %s.ys)",
                 key_str, key_str);
        return yas_raise_error("module-error", msg);
    }

    /* Absolute path so nested relative operations can't be mangled by the
     * current-file tracking flipping mid-load. */
    char *abs_path = realpath(path, NULL);
    free(path);
    if (!abs_path) {
        yas_gc_pop_roots(1); /* key */
        char msg[512];
        snprintf(msg, sizeof(msg), "module '%s': could not resolve path", key_str);
        return yas_raise_error("module-error", msg);
    }

    YasAtom mod_env;
    make_module(key_str, key, abs_path, parent, &lib, &mod_env);

    YasAtom ignore;
    int err = yas_eval_file(abs_path, mod_env, &ignore, 0);
    free(abs_path);

    if (err) {
        module_unregister(key_str, key);
        yas_gc_pop_roots(1); /* key */
        return err;
    }

    module_set_ready(lib);
    yas_gc_pop_roots(1); /* key */
    *out_lib = lib;
    return YAS_ERROR_OK;
}

/* Import-set resolution */

/* Resolve an import set to a Hash of {symbol -> value}. Raises a
 * module-error exception on any failure and returns non-zero. */
static int resolve_import_set(YasAtom set, YasAtom *out)
{
    if (set.type == YAS_ATOM_TYPE_PAIR) {
        YasAtom op = yas_car(set);
        if (op.type == YAS_ATOM_TYPE_SYMBOL) {
            const char *s = op.value.symbol;

            if (strcmp(s, "ONLY") == 0 || strcmp(s, "EXCEPT") == 0 ||
                strcmp(s, "PREFIX") == 0 || strcmp(s, "RENAME") == 0) {
                /* Shared shape validation: all four take an inner set as
                 * their first argument. */
                YasAtom rest = yas_cdr(set);
                if (rest.type != YAS_ATOM_TYPE_PAIR)
                    return yas_raise_error("module-error", "import set combinator: missing inner set");

                YasAtom child_map = yas_nil;
                int err = resolve_import_set(yas_car(rest), &child_map);
                if (err)
                    return err;

                YasAtom result = yas_make_hash();
                /* `child_map`/`result` are fresh, otherwise-unreachable
                 * locals - root both for the branch's duration. Once
                 * rooted, the raw struct YasHash* pulled from child_map
                 * stays valid: this collector never moves objects, and
                 * nothing here writes back into child_map, so its
                 * keys[]/values[] never get realloc'd mid-loop. */
                yas_gc_push_root(&child_map);
                yas_gc_push_root(&result);
                struct YasHash *h = child_map.value.hash;

                if (strcmp(s, "ONLY") == 0) {
                    /* (only SET id ...) */
                    YasAtom ids = yas_cdr(rest);
                    while (ids.type == YAS_ATOM_TYPE_PAIR) {
                        YasAtom id = yas_car(ids);
                        int found = 0;
                        for (size_t i = 0; i < h->size; i++) {
                            if (h->keys[i].type == YAS_ATOM_TYPE_SYMBOL &&
                                id.type == YAS_ATOM_TYPE_SYMBOL &&
                                h->keys[i].value.symbol == id.value.symbol) {
                                found = 1;
                                break;
                            }
                        }
                        if (!found) {
                            yas_gc_pop_roots(2);
                            char *form = yas_sprint_expr(id);
                            char msg[300];
                            snprintf(msg, sizeof(msg), "import 'only': selected name not exported: %s",
                                     form ? form : "?");
                            free(form);
                            return yas_raise_error("module-error", msg);
                        }
                        yas_hash_set(result, id, yas_hash_ref(child_map, id, yas_nil));
                        ids = yas_cdr(ids);
                    }
                    if (!yas_nilp(ids)) {
                        yas_gc_pop_roots(2);
                        return yas_raise_error("module-error", "import 'only': malformed name list");
                    }
                } else if (strcmp(s, "EXCEPT") == 0) {
                    /* (except SET id ...) */
                    YasAtom exceptions = yas_cdr(rest);
                    for (size_t i = 0; i < h->size; i++) {
                        YasAtom k = h->keys[i];
                        int skip = 0;
                        YasAtom p = exceptions;
                        while (p.type == YAS_ATOM_TYPE_PAIR) {
                            if (yas_car(p).type == YAS_ATOM_TYPE_SYMBOL &&
                                yas_car(p).value.symbol == k.value.symbol) {
                                skip = 1;
                                break;
                            }
                            p = yas_cdr(p);
                        }
                        if (!skip)
                            yas_hash_set(result, k, h->values[i]);
                    }
                } else if (strcmp(s, "PREFIX") == 0) {
                    /* (prefix SET p) */
                    YasAtom rest_tail = yas_cdr(rest);
                    YasAtom pfx = (rest_tail.type == YAS_ATOM_TYPE_PAIR)
                                      ? yas_car(rest_tail)
                                      : yas_nil;
                    if (pfx.type != YAS_ATOM_TYPE_SYMBOL ||
                        !yas_nilp(yas_cdr(rest_tail))) {
                        yas_gc_pop_roots(2);
                        return yas_raise_error("module-error",
                                               "import 'prefix': expected (prefix SET symbol)");
                    }
                    for (size_t i = 0; i < h->size; i++) {
                        YasAtom k = h->keys[i];
                        size_t n = strlen(pfx.value.symbol) + strlen(k.value.symbol) + 1;
                        char *buf = malloc(n);
                        snprintf(buf, n, "%s%s", pfx.value.symbol, k.value.symbol);
                        YasAtom new_key = yas_make_sym(buf);
                        free(buf);
                        yas_hash_set(result, new_key, h->values[i]);
                    }
                } else { /* RENAME */
                    /* (rename SET (old new) ...) */
                    YasAtom renames = yas_cdr(rest);
                    for (size_t i = 0; i < h->size; i++) {
                        YasAtom k = h->keys[i];
                        YasAtom new_key = k;
                        YasAtom p = renames;
                        while (p.type == YAS_ATOM_TYPE_PAIR) {
                            YasAtom pair = yas_car(p);
                            if (pair.type == YAS_ATOM_TYPE_PAIR &&
                                yas_car(pair).type == YAS_ATOM_TYPE_SYMBOL &&
                                k.type == YAS_ATOM_TYPE_SYMBOL &&
                                yas_car(pair).value.symbol == k.value.symbol) {
                                YasAtom new_name = yas_car(yas_cdr(pair));
                                if (new_name.type != YAS_ATOM_TYPE_SYMBOL) {
                                    yas_gc_pop_roots(2);
                                    return yas_raise_error(
                                        "module-error",
                                        "import 'rename': expected (old new) symbol pairs");
                                }
                                new_key = new_name;
                                break;
                            }
                            p = yas_cdr(p);
                        }
                        yas_hash_set(result, new_key, h->values[i]);
                    }
                }

                yas_gc_pop_roots(2); /* result, child_map */
                *out = result;
                return YAS_ERROR_OK;
            }
        }

        /* A pair that isn't a recognized combinator is now a hard error -
         * the old list-shaped library names ((yas base) etc.) no longer
         * exist. */
        char *form = yas_sprint_expr(set);
        char msg[300];
        snprintf(msg, sizeof(msg), "invalid import set: %s", form ? form : "?");
        free(form);
        return yas_raise_error("module-error", msg);
    }

    /* Base case: a bare module-name symbol. */
    char *key_str = module_key_from_symbol(set);
    if (!key_str) {
        char *form = yas_sprint_expr(set);
        char msg[300];
        snprintf(msg, sizeof(msg), "invalid import set: %s (expected a module name)",
                 form ? form : "?");
        free(form);
        return yas_raise_error("module-error", msg);
    }

    YasAtom lib = yas_nil;
    int err = load_module(key_str, &lib);
    free(key_str);
    if (err)
        return err;

    /* Copy every public binding out of the module's own frame (non
     * `_`-prefixed). yas_env_keys is frame-exact, so inherited base
     * bindings are NOT re-exported, and record metadata (*NAME*, state,
     * path) lives in the record hash rather than the env, so it never
     * leaks either. A module's surface is exactly what its top level
     * defines, minus underscore names - import order elsewhere can't
     * change that. */
    YasAtom mod_env = yas_hash_ref(lib, yas_make_sym("*ENV*"), yas_nil);
    YasAtom result = yas_make_hash();
    /* `result` is rooted across yas_env_keys() and the copy loop, both of
     * which allocate; `keys` accumulates through one yas_cons() per
     * binding. Both are fresh otherwise-unreachable locals. */
    yas_gc_push_root(&result);
    YasAtom keys = yas_env_keys(mod_env);
    yas_gc_push_root(&keys);

    YasAtom p = keys;
    while (p.type == YAS_ATOM_TYPE_PAIR) {
        YasAtom k = yas_car(p);
        if (k.value.symbol[0] != '_') {
            YasAtom v;
            if (yas_env_get(mod_env, k, &v) == YAS_ERROR_OK)
                yas_hash_set(result, k, v);
        }
        p = yas_cdr(p);
    }

    yas_gc_pop_roots(2); /* keys, result */
    *out = result;
    return YAS_ERROR_OK;
}

static int process_import_set(YasAtom import_set, YasAtom target_env)
{
    YasAtom bindings = yas_nil;
    int err = resolve_import_set(import_set, &bindings);
    if (err)
        return err;

    /* `bindings` is a fresh, otherwise-unreachable local - root it for
     * the loop's duration: yas_env_define() below can allocate (a fresh
     * binding slot growth), so this is not safe to leave unrooted now
     * that gc_alloc() itself can step the collector (docs/GC.md). */
    yas_gc_push_root(&bindings);
    struct YasHash *h = bindings.value.hash;
    for (size_t i = 0; i < h->size; i++)
        yas_env_define(target_env, h->keys[i], h->values[i]);
    yas_gc_pop_roots(1); /* bindings */
    return YAS_ERROR_OK;
}

static int yas_module_import_impl(YasAtom args, YasAtom env, YasAtom *result)
{
    /* (import set1 set2 ...) - called synchronously from eval_vm()'s own
     * IMPORT special-form dispatch (eval.c), never via a separate
     * yas_eval_expr() re-entry. `env` is that frame's own `env` local, so
     * it's the live EvalRoot->env for the whole duration of this call -
     * no separate root needed. `p` walks `args`, which is `yas_cdr(expr)`
     * at the point eval_vm called in, and expr isn't reassigned until the
     * next eval_vm loop iteration - so every cons `p` visits is reachable
     * transitively from EvalRoot->expr throughout, per docs/GC.md's
     * "Callers not affected" (both hold even though process_import_set()
     * can trigger nested module loads, which re-enter the evaluator and
     * push their own EvalRoot without ever popping this frame's).
     *
     * `args` is walked by explicit pair type rather than trusting
     * yas_nilp() alone to mark the end - a hand-built improper spine must
     * error, not walk off into data. */
    YasAtom p = args;
    while (p.type == YAS_ATOM_TYPE_PAIR) {
        int err = process_import_set(yas_car(p), env);
        if (err)
            return err;
        p = yas_cdr(p);
    }
    if (!yas_nilp(p))
        return YAS_ERROR_SYNTAX;
    *result = yas_nil;
    return YAS_ERROR_OK;
}

int yas_module_import(YasAtom args, YasAtom env, YasAtom *result)
{
    int r = yas_module_import_impl(args, env, result);
    return r;
}

