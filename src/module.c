/* Helper to register builtins into a module env */
static void reg_builtin(YasAtom env, const char *name, YasBuiltin fn)
{
    YasAtom sym = yas_make_sym(name);
    yas_env_define(env, sym, yas_make_builtin(fn));
}

static void reg_sym(YasAtom env, const char *name, YasAtom val)
{
    yas_env_define(env, yas_make_sym(name), val);
}

static YasAtom yas_define_native_module_impl(const char *name_str, YasAtom parent_env, YasAtom *out_env)
{
    ensure_registry();

    /* Parse "yas/base" -> interned symbols are built below one cons at a
     * time; see the rooting note inside the loop. */
    YasAtom name = yas_nil;
    YasAtom tail = yas_nil;

    /* `name`/`tail` accumulate across repeated yas_cons() calls below,
     * same shape as yas_list_create()'s accumulator (data.c) - root
     * `name` for the loop's duration. `tail` needs no separate root:
     * once yas_set_cdr(tail, node) links a new node in, it's reachable
     * by walking cdrs from `name`; only the very first node (before
     * `name`/`tail` are ever assigned) relies on `node` itself being
     * safe, which it is - it doesn't exist during its own yas_cons()
     * call's pacing (see gc_alloc()). */
    yas_gc_push_root(&name);

    char *s = strdup(name_str);
    char *token = strtok(s, "/");
    while (token) {
        /* Uppercase token */
        char *p = token;
        while (*p) {
            if (*p >= 'a' && *p <= 'z')
                *p -= 32;
            p++;
        }

        YasAtom sym = yas_make_sym(token);
        yas_gc_push_root(&sym);
        YasAtom node = yas_cons(sym, yas_nil);
        yas_gc_pop_roots(1); /* sym */
        if (yas_nilp(name)) {
            name = tail = node;
        } else {
            yas_set_cdr(tail, node);
            tail = node;
        }
        token = strtok(NULL, "/");
    }
    free(s);

    YasAtom lib = yas_make_hash();
    /* `name`'s root protects the cons spine through the allocations
     * below; `lib` takes over as the fresh, otherwise-unreachable local
     * that needs protecting - it isn't registered into
     * yas_library_registry (its only other reachability path) until the
     * yas_hash_set() at the end of this function, and the
     * yas_make_string()/yas_env_create() calls below definitely
     * allocate. */
    yas_gc_pop_roots(1); /* name */
    yas_gc_push_root(&lib);

    yas_hash_set(lib, yas_make_sym("*NAME*"), yas_make_string(name_str));
    yas_hash_set(lib, yas_make_sym("*STATE*"), yas_make_sym(MODULE_STATE_READY));
    yas_hash_set(lib, yas_make_sym("*PATH*"), yas_nil);
    YasAtom env = yas_env_create(parent_env);
    /* Module-boundary marker for yas_env_set() - see make_module(). */
    env.value.env->module_boundary = 1;
    yas_hash_set(lib, yas_make_sym("*ENV*"), env);

    *out_env = env;

    YasAtom key = yas_make_string(name_str);
    yas_hash_set(yas_library_registry, key, lib);

    yas_gc_pop_roots(1); /* lib */
    return lib;
}

YasAtom yas_define_native_module(const char *name_str, YasAtom parent_env, YasAtom *out_env)
{
    YasAtom r = yas_define_native_module_impl(name_str, parent_env, out_env);
    return r;
}


