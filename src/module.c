/* Note on rooting below: symbol atoms are NOT GC objects - yas_make_sym()
 * interns a plain malloc'd string in data.c's symbol table and returns a
 * value atom pointing at it, so freshly made symbols need no roots. Only
 * the cons cells / hashes / strings / envs built around them do. */

