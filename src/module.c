/* File-based module system.
 *
 * A module IS a file: its top-level forms evaluate exactly once, into a
 * fresh module environment, and importing copies the module's public
 * bindings (everything except `_`-prefixed names) into the importer's
 * frame. There are no declaration wrappers and no export lists - see
 * docs/LANGUAGE_REFERENCE.md's "Modules" section for the language-level
 * contract.
 *
 * Import sets:
 *
 *   SET := SYMBOL                       module name ("yas/base")
 *        | (only   SET id ...)          keep only these names
 *        | (except SET id ...)          keep everything but these
 *        | (prefix SET p)               prepend p to every name
 *        | (rename SET (old new) ...)   rename individual names
 *
 * Sets compose arbitrarily; the combinators operate on the binding map
 * their inner set resolves to, so e.g. `(only (prefix math m/) m/sqrt)`
 * is legal.
 *
 * Module records live in yas_library_registry (a GC-rooted global hash)
 * keyed by the lowercased module name string. A record is a hash with:
 *
 *   *NAME*  - canonical key string
 *   *STATE* - LOADING while the body evaluates, READY afterwards; a
 *             registry hit on a LOADING module is a circular import
 *   *PATH*  - source path (string), or "<builtin>" / nil for native or
 *             C-less embedded modules
 *   *ENV*   - the module environment itself
 *
 * Every module env chains to yas/base's env as its PARENT - one shared
 * "builtins layer" frame behind all modules, Python-style. Module code
 * sees base's bindings by fallthrough, but a module's public surface is
 * only its OWN frame's bindings (imports enumerate with frame-exact
 * yas_env_keys), so base is never re-exported through an importing
 * module and import order can't change what an importer receives.
 * yas/base itself is that chain's root; its native and Lisp halves share
 * one env.
 *
 * The shared parent never sees writes: every module env carries
 * module_boundary (struct YasEnv), and yas_env_set() treats the first
 * such frame on its parent walk as terminal - a (set! ...) on an
 * INHERITED name shadows into that frame instead of writing through to
 * base. The shadow lives in the module's own frame, so it counts as
 * part of the module's public surface on later imports; sibling modules
 * and base itself are untouched either way. See docs/
 * LANGUAGE_REFERENCE.md's "Modules" section.
 *
 * Resolution order per import: registry cache -> native C loaders ->
 * embedded stdlib sources (stdlib.h, generated by embed.py) ->
 * filesystem search paths, with the directory of the file performing the
 * import tried before the global search paths. Embedded/native modules
 * always beat same-named files on disk.
 */

